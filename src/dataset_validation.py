import logging

import pandas as pd


# ---------------------------------------------------------------------------
# Logging configuration
# ---------------------------------------------------------------------------

# Configure structured logging so that validation progress, warnings,
# and errors are clearly visible when the script runs.
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(name)s | %(message)s"
)

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Dataset configuration
# ---------------------------------------------------------------------------

# Processed metadata files generated by the ETL pipelines.
IMAGE_METADATA_PATH = "data/processed/image_metadata.csv"
VIDEO_METADATA_PATH = "data/processed/video_metadata.csv"

# Label file used to evaluate whether images are ready for ML workflows.
IMAGE_LABELS_PATH = "data/labels/image_labels.csv"


def load_csv(file_path, dataset_name):
    """
    Load a CSV file used by the dataset validation workflow.

    Args:
        file_path: Path to the CSV file.
        dataset_name: Human-readable dataset name used in log messages.

    Returns:
        pandas.DataFrame if the file loads successfully, otherwise None.
    """

    try:
        logger.info(
            "Loading %s from %s.",
            dataset_name,
            file_path
        )

        dataframe = pd.read_csv(file_path)

        logger.info(
            "%s loaded successfully with %d record(s).",
            dataset_name,
            len(dataframe)
        )

        return dataframe

    except FileNotFoundError:
        logger.error(
            "%s file was not found: %s",
            dataset_name,
            file_path
        )

        return None

    except pd.errors.EmptyDataError:
        logger.error(
            "%s file is empty: %s",
            dataset_name,
            file_path
        )

        return None

    except Exception:
        logger.exception(
            "Unexpected error while loading %s.",
            dataset_name
        )

        return None


def validate_image_dataset(image_df):
    """
    Validate processed image metadata.

    Checks include corruption, blur, brightness quality, duplicate hashes,
    missing dimensions, and invalid dimensions.

    Returns:
        Total number of image validation issues.
    """

    logger.info(
        "Starting image dataset validation."
    )

    print("\nIMAGE DATASET VALIDATION")
    print("------------------------")

    total_images = len(image_df)

    print(f"Total image records: {total_images}")

    # -----------------------------------------------------------------------
    # Check 1: Corrupted images
    # -----------------------------------------------------------------------

    # The metadata pipeline marks files that OpenCV cannot read
    # using the is_corrupted field.
    corrupted_count = image_df[
        "is_corrupted"
    ].sum()

    print(
        f"Corrupted images: {corrupted_count}"
    )

    # -----------------------------------------------------------------------
    # Check 2: Blurry images
    # -----------------------------------------------------------------------

    # Any blur status other than "Normal" is considered a quality issue.
    blurry_count = (
        image_df["blur_warning"] != "Normal"
    ).sum()

    print(
        f"Blurry images: {blurry_count}"
    )

    # -----------------------------------------------------------------------
    # Check 3: Brightness issues
    # -----------------------------------------------------------------------

    # Images marked as too dark or too bright are counted as issues.
    brightness_issue_count = (
        image_df["brightness_warning"] != "Normal"
    ).sum()

    print(
        f"Images with brightness issues: "
        f"{brightness_issue_count}"
    )

    # -----------------------------------------------------------------------
    # Check 4: Duplicate images
    # -----------------------------------------------------------------------

    # SHA-256 hashes provide a content-based method for detecting
    # duplicate image files.
    duplicate_count = (
        image_df["sha256"]
        .duplicated()
        .sum()
    )

    print(
        f"Duplicate images: {duplicate_count}"
    )

    # -----------------------------------------------------------------------
    # Check 5: Missing image dimensions
    # -----------------------------------------------------------------------

    missing_dimensions = (
        image_df[
            ["width", "height"]
        ]
        .isnull()
        .any(axis=1)
        .sum()
    )

    print(
        f"Images with missing dimensions: "
        f"{missing_dimensions}"
    )

    # -----------------------------------------------------------------------
    # Check 6: Invalid image dimensions
    # -----------------------------------------------------------------------

    # Width and height should always contain positive values.
    invalid_dimensions = (
        (image_df["width"] <= 0)
        | (image_df["height"] <= 0)
    ).sum()

    print(
        f"Images with invalid dimensions: "
        f"{invalid_dimensions}"
    )

    # -----------------------------------------------------------------------
    # Calculate total image issues
    # -----------------------------------------------------------------------

    total_image_issues = (
        corrupted_count
        + blurry_count
        + brightness_issue_count
        + duplicate_count
        + missing_dimensions
        + invalid_dimensions
    )

    print(
        f"Total image validation issues found: "
        f"{total_image_issues}"
    )

    if total_image_issues == 0:
        logger.info(
            "Image dataset validation completed with no issues."
        )
    else:
        logger.warning(
            "Image dataset validation found %d issue(s).",
            total_image_issues
        )

    return total_image_issues


def validate_video_dataset(video_df):
    """
    Validate processed video metadata.

    Checks include corruption, duplicate hashes, dimensions,
    frame rate, frame count, and video duration.

    Returns:
        Total number of video validation issues.
    """

    logger.info(
        "Starting video dataset validation."
    )

    print("\nVIDEO DATASET VALIDATION")
    print("------------------------")

    total_videos = len(video_df)

    print(
        f"Total video records: {total_videos}"
    )

    # -----------------------------------------------------------------------
    # Check 1: Corrupted videos
    # -----------------------------------------------------------------------

    corrupted_video_count = video_df[
        "is_corrupted"
    ].sum()

    print(
        f"Corrupted videos: {corrupted_video_count}"
    )

    # -----------------------------------------------------------------------
    # Check 2: Duplicate videos
    # -----------------------------------------------------------------------

    # SHA-256 hashes are used to identify duplicate video content.
    duplicate_video_count = (
        video_df["sha256"]
        .duplicated()
        .sum()
    )

    print(
        f"Duplicate videos: {duplicate_video_count}"
    )

    # -----------------------------------------------------------------------
    # Check 3: Missing video dimensions
    # -----------------------------------------------------------------------

    missing_video_dimensions = (
        video_df[
            ["width", "height"]
        ]
        .isnull()
        .any(axis=1)
        .sum()
    )

    print(
        f"Videos with missing dimensions: "
        f"{missing_video_dimensions}"
    )

    # -----------------------------------------------------------------------
    # Check 4: Invalid video dimensions
    # -----------------------------------------------------------------------

    invalid_video_dimensions = (
        (video_df["width"] <= 0)
        | (video_df["height"] <= 0)
    ).sum()

    print(
        f"Videos with invalid dimensions: "
        f"{invalid_video_dimensions}"
    )

    # -----------------------------------------------------------------------
    # Check 5: Invalid frames per second
    # -----------------------------------------------------------------------

    # Valid videos should have a positive FPS value.
    invalid_fps_count = (
        video_df["fps"].isnull()
        | (video_df["fps"] <= 0)
    ).sum()

    print(
        f"Videos with invalid FPS: "
        f"{invalid_fps_count}"
    )

    # -----------------------------------------------------------------------
    # Check 6: Invalid frame count
    # -----------------------------------------------------------------------

    # A readable video should contain at least one frame.
    invalid_frame_count = (
        video_df["frame_count"].isnull()
        | (video_df["frame_count"] <= 0)
    ).sum()

    print(
        f"Videos with invalid frame count: "
        f"{invalid_frame_count}"
    )

    # -----------------------------------------------------------------------
    # Check 7: Invalid duration
    # -----------------------------------------------------------------------

    # Video duration must be a positive value.
    invalid_duration_count = (
        video_df["duration_seconds"].isnull()
        | (video_df["duration_seconds"] <= 0)
    ).sum()

    print(
        f"Videos with invalid duration: "
        f"{invalid_duration_count}"
    )

    # -----------------------------------------------------------------------
    # Calculate total video issues
    # -----------------------------------------------------------------------

    total_video_issues = (
        corrupted_video_count
        + duplicate_video_count
        + missing_video_dimensions
        + invalid_video_dimensions
        + invalid_fps_count
        + invalid_frame_count
        + invalid_duration_count
    )

    print(
        f"Total video validation issues found: "
        f"{total_video_issues}"
    )

    if total_video_issues == 0:
        logger.info(
            "Video dataset validation completed with no issues."
        )
    else:
        logger.warning(
            "Video dataset validation found %d issue(s).",
            total_video_issues
        )

    return total_video_issues


def validate_image_labels(image_df, labels_df):
    """
    Validate image labels used for machine-learning preparation.

    Checks include unknown labels, missing labels, duplicate label
    records, and images that do not have a corresponding label.

    Returns:
        Total number of label validation issues.
    """

    logger.info(
        "Starting image label validation."
    )

    print("\nIMAGE LABEL VALIDATION")
    print("----------------------")

    print(
        f"Total labelled image records: "
        f"{len(labels_df)}"
    )

    # -----------------------------------------------------------------------
    # Check 1: Unknown labels
    # -----------------------------------------------------------------------

    # "unknown" represents images that have not been assigned
    # a confident class label.
    unknown_label_count = (
        labels_df["label"] == "unknown"
    ).sum()

    print(
        f"Images with unknown labels: "
        f"{unknown_label_count}"
    )

    # -----------------------------------------------------------------------
    # Check 2: Missing labels
    # -----------------------------------------------------------------------

    missing_label_count = (
        labels_df["label"]
        .isnull()
        .sum()
    )

    print(
        f"Images with missing labels: "
        f"{missing_label_count}"
    )

    # -----------------------------------------------------------------------
    # Check 3: Duplicate label records
    # -----------------------------------------------------------------------

    # Each image should normally have one label record.
    duplicate_label_records = (
        labels_df["file_path"]
        .duplicated()
        .sum()
    )

    print(
        f"Duplicate label records: "
        f"{duplicate_label_records}"
    )

    # -----------------------------------------------------------------------
    # Check 4: Images without label records
    # -----------------------------------------------------------------------

    # Compare image metadata with the label file to make sure every
    # processed image appears in the labelling dataset.
    unlabelled_images = (
        ~image_df["file_path"].isin(
            labels_df["file_path"]
        )
    ).sum()

    print(
        f"Images without label records: "
        f"{unlabelled_images}"
    )

    # -----------------------------------------------------------------------
    # Check 5: Class distribution
    # -----------------------------------------------------------------------

    # Class distribution provides a simple view of dataset balance.
    label_distribution = (
        labels_df["label"]
        .value_counts()
    )

    print("\nLabel distribution:")
    print(
        label_distribution.to_string()
    )

    logger.info(
        "Image label distribution:\n%s",
        label_distribution.to_string()
    )

    # -----------------------------------------------------------------------
    # Calculate total label issues
    # -----------------------------------------------------------------------

    total_label_issues = (
        unknown_label_count
        + missing_label_count
        + duplicate_label_records
        + unlabelled_images
    )

    print(
        f"\nTotal label validation issues found: "
        f"{total_label_issues}"
    )

    if total_label_issues == 0:
        logger.info(
            "Image label validation completed with no issues."
        )
    else:
        logger.warning(
            "Image label validation found %d issue(s).",
            total_label_issues
        )

    return total_label_issues


def display_overall_summary(
    image_df,
    video_df,
    total_image_issues,
    total_video_issues,
    total_label_issues
):
    """
    Display the overall SentinelVision dataset validation result.

    Combines image, video, and label validation issues into one
    final dataset-readiness summary.
    """

    total_dataset_issues = (
        total_image_issues
        + total_video_issues
        + total_label_issues
    )

    print("\nOVERALL VALIDATION SUMMARY")
    print("--------------------------")

    print(
        f"Total images: {len(image_df)}"
    )

    print(
        f"Total videos: {len(video_df)}"
    )

    print(
        f"Total validation issues: "
        f"{total_dataset_issues}"
    )

    if total_dataset_issues == 0:
        print(
            "Dataset validation status: PASS"
        )

        logger.info(
            "Dataset validation status: PASS"
        )

    else:
        print(
            "Dataset validation status: ISSUES FOUND"
        )

        logger.warning(
            "Dataset validation status: ISSUES FOUND | "
            "Total issues: %d",
            total_dataset_issues
        )

    return total_dataset_issues


def run_dataset_validation():
    """
    Run the complete SentinelVision dataset validation workflow.

    The workflow validates image metadata, video metadata, image labels,
    and then generates an overall dataset quality summary.
    """

    logger.info(
        "Starting SentinelVision dataset validation."
    )

    # -----------------------------------------------------------------------
    # Step 1: Load validation datasets
    # -----------------------------------------------------------------------

    image_df = load_csv(
        IMAGE_METADATA_PATH,
        "image metadata"
    )

    video_df = load_csv(
        VIDEO_METADATA_PATH,
        "video metadata"
    )

    labels_df = load_csv(
        IMAGE_LABELS_PATH,
        "image labels"
    )

    # Stop validation if any required dataset could not be loaded.
    if (
        image_df is None
        or video_df is None
        or labels_df is None
    ):
        logger.error(
            "Dataset validation stopped because one or more "
            "required files could not be loaded."
        )

        return

    # -----------------------------------------------------------------------
    # Step 2: Validate image metadata
    # -----------------------------------------------------------------------

    total_image_issues = validate_image_dataset(
        image_df
    )

    # -----------------------------------------------------------------------
    # Step 3: Validate video metadata
    # -----------------------------------------------------------------------

    total_video_issues = validate_video_dataset(
        video_df
    )

    # -----------------------------------------------------------------------
    # Step 4: Validate image labels
    # -----------------------------------------------------------------------

    total_label_issues = validate_image_labels(
        image_df,
        labels_df
    )

    # -----------------------------------------------------------------------
    # Step 5: Generate overall validation summary
    # -----------------------------------------------------------------------

    display_overall_summary(
        image_df,
        video_df,
        total_image_issues,
        total_video_issues,
        total_label_issues
    )

    logger.info(
        "SentinelVision dataset validation workflow completed."
    )


if __name__ == "__main__":
    run_dataset_validation()

    